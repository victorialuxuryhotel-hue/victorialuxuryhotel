-- =============================================================================
-- Victoria Luxury Hotel: schema (Cloudflare D1 / SQLite)
--
-- Concepts
--   room_categories  what a guest books (Standard, Deluxe, Suite, Apartment)
--   rooms            the physical rooms staff assign
--   reservations     one stay, for one category, optionally assigned a room
--   payments         money movements against a reservation (never merged into it)
--
-- Conventions
--   * Money is integer kobo (NGN minor unit, as Paystack uses).
--   * Stay dates are hotel-local 'YYYY-MM-DD' text; a stay covers nights
--     [check_in, check_out), so the check-out day is free for the next arrival.
--   * Timestamps are UTC ISO-8601 text with milliseconds ('…T…:…:….sssZ'),
--     the format JavaScript's toISOString() writes, so text order = time order.
--   * Ids are UUID text generated by the app (crypto.randomUUID()).
--   * Booleans are INTEGER 0/1.
--
-- Business rules that must hold for every writer live in triggers
-- (0002–0004). Multi-step actions are app code that runs as one D1 batch
-- (atomic); D1 runs writes one at a time, so a trigger's check and the write
-- it guards can't be interleaved with another request.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Request context: who is acting, and why (status-change reason).
-- The app writes this row as the first statement of a batch and deletes it as
-- the last, so audit and history triggers can attribute the change. A failed
-- batch rolls back with it. No row = the system (webhook, scheduled job).
-- ---------------------------------------------------------------------------
CREATE TABLE _ctx (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  actor_id TEXT,
  reason TEXT
);

-- One row per date. SQLite triggers can't use recursive CTEs, so the capacity
-- trigger walks the nights of a stay through this table.
CREATE TABLE calendar (d TEXT PRIMARY KEY) WITHOUT ROWID;
WITH RECURSIVE days(d) AS (
  SELECT '2024-01-01'
  UNION ALL SELECT date(d, '+1 day') FROM days WHERE d < '2045-12-31'
)
INSERT INTO calendar (d) SELECT d FROM days;

-- ---------------------------------------------------------------------------
-- Hotel settings (single row)
-- ---------------------------------------------------------------------------
CREATE TABLE hotel_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  check_in_time TEXT NOT NULL DEFAULT '14:00' CHECK (check_in_time GLOB '[0-2][0-9]:[0-5][0-9]'),
  check_out_time TEXT NOT NULL DEFAULT '12:00' CHECK (check_out_time GLOB '[0-2][0-9]:[0-5][0-9]'),
  -- How long an unpaid website reservation holds inventory while the guest pays.
  website_hold_minutes INTEGER NOT NULL DEFAULT 30 CHECK (website_hold_minutes BETWEEN 10 AND 1440),
  -- How long a staff-created unpaid reservation holds inventory.
  staff_hold_hours INTEGER NOT NULL DEFAULT 24 CHECK (staff_hold_hours BETWEEN 1 AND 336),
  -- Configurable: the hotel has not confirmed the 24–48 h rule. NULL = not yet set.
  cancellation_policy TEXT CHECK (length(cancellation_policy) <= 2000),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
INSERT INTO hotel_settings (id) VALUES (1);

-- ---------------------------------------------------------------------------
-- Staff (identity is Clerk; role and status live here, the source of truth)
-- ---------------------------------------------------------------------------
CREATE TABLE staff_profiles (
  id TEXT PRIMARY KEY,
  -- Set the first time the invited person signs in with Clerk.
  clerk_user_id TEXT UNIQUE,
  full_name TEXT NOT NULL CHECK (length(trim(full_name)) BETWEEN 2 AND 120),
  email TEXT NOT NULL UNIQUE CHECK (email = lower(email) AND email LIKE '%_@_%._%'),
  phone TEXT,
  role TEXT NOT NULL CHECK (role IN ('owner', 'general_manager', 'front_desk')),
  -- Deactivate rather than delete so audit history keeps its actor.
  is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- ---------------------------------------------------------------------------
-- Accommodation
-- ---------------------------------------------------------------------------
CREATE TABLE room_categories (
  id TEXT PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE CHECK (
    length(slug) BETWEEN 1 AND 60 AND slug NOT GLOB '*[^a-z0-9-]*'
    AND slug NOT GLOB '-*' AND slug NOT GLOB '*-' AND slug NOT GLOB '*--*'
  ),
  name TEXT NOT NULL UNIQUE CHECK (length(trim(name)) BETWEEN 2 AND 80),
  short_description TEXT,
  description TEXT,
  nightly_rate_kobo INTEGER NOT NULL CHECK (nightly_rate_kobo > 0),
  max_occupancy INTEGER NOT NULL CHECK (max_occupancy BETWEEN 1 AND 20),
  -- JSON array of strings.
  amenities TEXT NOT NULL DEFAULT '[]' CHECK (json_valid(amenities) AND json_type(amenities) = 'array'),
  is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE TABLE room_category_images (
  id TEXT PRIMARY KEY,
  category_id TEXT NOT NULL REFERENCES room_categories (id) ON DELETE CASCADE,
  -- Object key in the photos R2 bucket.
  storage_path TEXT NOT NULL UNIQUE,
  alt_text TEXT NOT NULL CHECK (length(trim(alt_text)) BETWEEN 3 AND 200),
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_cover INTEGER NOT NULL DEFAULT 0 CHECK (is_cover IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX room_category_images_category_idx ON room_category_images (category_id, sort_order);
CREATE UNIQUE INDEX room_category_images_one_cover ON room_category_images (category_id) WHERE is_cover = 1;

CREATE TABLE rooms (
  id TEXT PRIMARY KEY,
  room_number TEXT NOT NULL UNIQUE CHECK (length(trim(room_number)) BETWEEN 1 AND 10),
  category_id TEXT NOT NULL REFERENCES room_categories (id) ON DELETE RESTRICT,
  floor TEXT,
  service_status TEXT NOT NULL DEFAULT 'in_service' CHECK (service_status IN ('in_service', 'maintenance')),
  maintenance_note TEXT,
  -- Simple readiness indicator; a future housekeeping module updates it.
  readiness TEXT NOT NULL DEFAULT 'ready' CHECK (readiness IN ('needs_cleaning', 'cleaning_in_progress', 'ready')),
  -- 0 = permanently removed from inventory (kept for history).
  is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX rooms_category_idx ON rooms (category_id);

-- ---------------------------------------------------------------------------
-- Guests
-- ---------------------------------------------------------------------------
CREATE TABLE guests (
  id TEXT PRIMARY KEY,
  full_name TEXT NOT NULL CHECK (length(trim(full_name)) BETWEEN 2 AND 120),
  -- Optional (walk-ins may not give one). Stored lower-case.
  email TEXT CHECK (email IS NULL OR (email = lower(email) AND email LIKE '%_@_%._%' AND email NOT LIKE '% %')),
  phone TEXT,
  notes TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE UNIQUE INDEX guests_email_key ON guests (email) WHERE email IS NOT NULL;
CREATE INDEX guests_phone_idx ON guests (phone) WHERE phone IS NOT NULL;
CREATE INDEX guests_name_idx ON guests (lower(full_name));

-- ---------------------------------------------------------------------------
-- Reservations
-- ---------------------------------------------------------------------------
CREATE TABLE reservations (
  id TEXT PRIMARY KEY,
  -- Human-friendly, non-sequential reference, e.g. VL-7KQ3PM (made by the app).
  reference TEXT NOT NULL UNIQUE CHECK (length(reference) = 9 AND substr(reference, 1, 3) = 'VL-' AND reference = upper(reference)),
  -- Unguessable token for the guest's confirmation page.
  public_token TEXT NOT NULL UNIQUE,
  guest_id TEXT NOT NULL REFERENCES guests (id) ON DELETE RESTRICT,
  category_id TEXT NOT NULL REFERENCES room_categories (id) ON DELETE RESTRICT,
  room_id TEXT REFERENCES rooms (id) ON DELETE RESTRICT,
  check_in TEXT NOT NULL CHECK (date(check_in) = check_in),  -- a valid YYYY-MM-DD date
  check_out TEXT NOT NULL CHECK (date(check_out) = check_out),
  nights INTEGER GENERATED ALWAYS AS (CAST(julianday(check_out) - julianday(check_in) AS INTEGER)) STORED,
  guest_count INTEGER NOT NULL CHECK (guest_count BETWEEN 1 AND 20),
  -- Price snapshot at booking time; later rate changes do not alter it.
  nightly_rate_kobo INTEGER NOT NULL CHECK (nightly_rate_kobo > 0),
  total_amount_kobo INTEGER NOT NULL CHECK (total_amount_kobo > 0),
  currency TEXT NOT NULL DEFAULT 'NGN' CHECK (currency = 'NGN'),
  status TEXT NOT NULL DEFAULT 'pending_payment' CHECK (status IN (
    'pending_payment', 'confirmed', 'checked_in', 'checked_out', 'cancelled', 'expired', 'no_show'
  )),
  source TEXT NOT NULL CHECK (source IN ('website', 'walk_in', 'phone', 'whatsapp', 'staff')),
  special_requests TEXT CHECK (length(special_requests) <= 1000),
  hold_expires_at TEXT,
  confirmed_at TEXT,
  checked_in_at TEXT,
  checked_out_at TEXT,
  cancelled_at TEXT,
  cancellation_reason TEXT,
  -- Set when something needs a human. Cleared by a manager.
  attention_reason TEXT,
  created_by TEXT REFERENCES staff_profiles (id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),

  CHECK (check_out > check_in),
  CHECK (julianday(check_out) - julianday(check_in) <= 90),
  CHECK (total_amount_kobo = nightly_rate_kobo * CAST(julianday(check_out) - julianday(check_in) AS INTEGER)),
  CHECK (status <> 'pending_payment' OR hold_expires_at IS NOT NULL),
  CHECK (status NOT IN ('checked_in', 'checked_out') OR room_id IS NOT NULL),
  CHECK (source <> 'website' OR created_by IS NULL)
);
CREATE INDEX reservations_check_in_idx ON reservations (check_in);
CREATE INDEX reservations_check_out_idx ON reservations (check_out);
CREATE INDEX reservations_status_idx ON reservations (status);
CREATE INDEX reservations_guest_idx ON reservations (guest_id);
CREATE INDEX reservations_room_idx ON reservations (room_id, check_in, check_out) WHERE room_id IS NOT NULL;
CREATE INDEX reservations_category_dates_idx ON reservations (category_id, check_in, check_out);
CREATE INDEX reservations_pending_hold_idx ON reservations (hold_expires_at) WHERE status = 'pending_payment';

CREATE TABLE reservation_status_history (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  reservation_id TEXT NOT NULL REFERENCES reservations (id) ON DELETE CASCADE,
  from_status TEXT,
  to_status TEXT NOT NULL,
  changed_by TEXT REFERENCES staff_profiles (id) ON DELETE SET NULL,
  reason TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX reservation_status_history_reservation_idx ON reservation_status_history (reservation_id, created_at);

-- ---------------------------------------------------------------------------
-- Payments
-- ---------------------------------------------------------------------------
CREATE TABLE payments (
  id TEXT PRIMARY KEY,
  -- Room-reservation payments only; other departments get their own tables.
  reservation_id TEXT NOT NULL REFERENCES reservations (id) ON DELETE RESTRICT,
  kind TEXT NOT NULL DEFAULT 'payment' CHECK (kind IN ('payment', 'refund')),
  amount_kobo INTEGER NOT NULL CHECK (amount_kobo > 0),
  currency TEXT NOT NULL DEFAULT 'NGN' CHECK (currency = 'NGN'),
  provider TEXT NOT NULL CHECK (provider IN ('paystack', 'offline')),
  method TEXT CHECK (method IN ('card', 'bank_transfer', 'cash', 'pos_terminal', 'ussd', 'other')),
  -- Paystack transaction reference (ours) or the offline reference.
  provider_reference TEXT,
  provider_channel TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'successful', 'failed', 'abandoned')),
  paid_at TEXT,
  -- When our server confirmed it: Paystack verify API, or staff confirming receipt.
  verified_at TEXT,
  gateway_response TEXT,
  receipt_number TEXT UNIQUE,
  recorded_by TEXT REFERENCES staff_profiles (id) ON DELETE SET NULL,
  notes TEXT CHECK (length(notes) <= 1000),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),

  CHECK (status <> 'successful' OR (verified_at IS NOT NULL AND paid_at IS NOT NULL)),
  CHECK (provider <> 'offline' OR recorded_by IS NOT NULL),
  CHECK (provider <> 'paystack' OR provider_reference IS NOT NULL),
  CHECK (receipt_number IS NULL OR status = 'successful')
);
CREATE UNIQUE INDEX payments_provider_reference_key ON payments (provider, provider_reference) WHERE provider_reference IS NOT NULL;
CREATE INDEX payments_reservation_idx ON payments (reservation_id);
CREATE INDEX payments_status_paid_at_idx ON payments (status, paid_at);

-- Gapless receipt numbers: a counter updated in the same transaction as the
-- payment (a failed batch rolls it back, so no holes).
CREATE TABLE receipt_counters (
  year INTEGER PRIMARY KEY,
  last_number INTEGER NOT NULL CHECK (last_number >= 0)
);

-- Raw provider notifications, kept for idempotency and investigation.
CREATE TABLE payment_events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  provider TEXT NOT NULL CHECK (provider IN ('paystack', 'offline')),
  event_type TEXT NOT NULL,
  provider_reference TEXT,
  -- Paystack retries deliver an identical body; the hash makes retries no-ops.
  payload_hash TEXT NOT NULL UNIQUE,
  payload TEXT NOT NULL CHECK (json_valid(payload)),
  received_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  processed_at TEXT,
  processing_error TEXT
);
CREATE INDEX payment_events_reference_idx ON payment_events (provider, provider_reference);

-- ---------------------------------------------------------------------------
-- Activity / audit log (append-only; enforced in 0004)
-- ---------------------------------------------------------------------------
CREATE TABLE activity_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  actor_id TEXT REFERENCES staff_profiles (id) ON DELETE SET NULL,
  actor_type TEXT NOT NULL CHECK (actor_type IN ('staff', 'system', 'guest')),
  action TEXT NOT NULL CHECK (action GLOB '[a-z]*.[a-z]*' AND action NOT GLOB '*[^a-z_.]*'),
  entity_type TEXT NOT NULL,
  entity_id TEXT,
  summary TEXT NOT NULL,
  -- Context only. Never card data, tokens or full provider payloads.
  metadata TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(metadata)),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX activity_log_entity_idx ON activity_log (entity_type, entity_id, created_at DESC);
CREATE INDEX activity_log_created_idx ON activity_log (created_at DESC);
CREATE INDEX activity_log_actor_idx ON activity_log (actor_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Email outbox: rows are written by triggers in the same transaction as the
-- change that causes them, then delivered (and retried) by the app.
-- ---------------------------------------------------------------------------
CREATE TABLE email_outbox (
  id TEXT PRIMARY KEY DEFAULT (lower(hex(randomblob(16)))),
  kind TEXT NOT NULL CHECK (kind IN ('booking_confirmed', 'payment_received', 'reservation_cancelled')),
  reservation_id TEXT NOT NULL REFERENCES reservations (id) ON DELETE CASCADE,
  payment_id TEXT REFERENCES payments (id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'skipped', 'failed')),
  attempts INTEGER NOT NULL DEFAULT 0,
  last_error TEXT,
  next_attempt_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  -- Set when a sender claims the row; cleared when it finishes.
  claim_id TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  sent_at TEXT
);
-- One of each per reservation (payment receipts: one per payment).
CREATE UNIQUE INDEX email_outbox_once_per_reservation ON email_outbox (kind, reservation_id) WHERE kind <> 'payment_received';
CREATE UNIQUE INDEX email_outbox_once_per_payment ON email_outbox (payment_id) WHERE kind = 'payment_received';
CREATE INDEX email_outbox_due_idx ON email_outbox (next_attempt_at) WHERE status = 'pending';

-- ---------------------------------------------------------------------------
-- Rate limiting (fixed window) for anonymous website actions. Keys are hashed
-- by the app; no raw IP addresses are stored.
-- ---------------------------------------------------------------------------
CREATE TABLE rate_limit_hits (
  key TEXT NOT NULL,
  window_start TEXT NOT NULL,
  hits INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (key, window_start)
) WITHOUT ROWID;

-- ---------------------------------------------------------------------------
-- Website photos (hero, pool, spa, gallery…). Files live in R2.
-- ---------------------------------------------------------------------------
CREATE TABLE site_photos (
  id TEXT PRIMARY KEY,
  slot TEXT NOT NULL CHECK (slot IN (
    'hero', 'welcome', 'pool', 'spa', 'bar', 'restaurant', 'conference',
    'exterior', 'reception', 'about', 'gallery'
  )),
  gallery_group TEXT CHECK (gallery_group IN ('Rooms', 'Pool & spa', 'Dining', 'The hotel')),
  storage_path TEXT NOT NULL UNIQUE,
  alt_text TEXT NOT NULL CHECK (length(trim(alt_text)) BETWEEN 3 AND 200),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  CHECK ((slot = 'gallery') = (gallery_group IS NOT NULL))
);
-- Every place except the gallery holds exactly one photo.
CREATE UNIQUE INDEX site_photos_one_per_slot ON site_photos (slot) WHERE slot <> 'gallery';
CREATE INDEX site_photos_gallery_idx ON site_photos (gallery_group, sort_order) WHERE slot = 'gallery';
